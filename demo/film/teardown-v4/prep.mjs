#!/usr/bin/env node
// Prepares the simulator's inputs from this repo (run from anywhere: node demo/film/teardown-v4/prep.mjs):
//   gen/package.json  the sample package's real numbers, read from landsight/synth through the repo's Python
//   gen/sheets.js     the sheet drawings the film shows, as data URLs (from public/v2/sheets, made by stage-v2-sheets.py)
//   timeline.json     the beats in seconds (for the review stills: capture.mjs --stills beats --timeline timeline.json)
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../../..');
const GEN = path.join(HERE, 'gen');
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
fs.mkdirSync(GEN, {recursive: true});

// 1. the package: every dimension the model is built from comes from the generator that drew the sample DXFs
const PY = `
import json
from landsight.synth import site as S, tower as T, sheets as SH
b = lambda r: [float(v) for v in r]
pav = {S.PAVING_CODES[k]: {"name": S.PAVING_EN[k].capitalize(), "box": b(v[0])} for k, v in S.PAVING.items()}
print(json.dumps({
  "site": {"w": S.SITE_W, "h": S.SITE_H,
           "tree": {"r": S.TREE_R, "spacing": S.TREE_SPACING, "y": S.TREE_Y, "x0": S.TREE_X0, "n": S.TREE_N},
           "hedge": {"x": b(S.HEDGE_X), "y": b(S.HEDGE_Y), "spacing": S.HEDGE_SPACING, "n": S.hedge_count()},
           "beds": b(S.SHRUB_BOX), "lawn": b(S.LAWN_BOX), "paving": pav, "planter": b(S.PLANTER_BOX),
           "existing": b(S.EXISTING_TREE), "rpz": S.RPZ_FACTOR, "roadTree": b(S.ROAD_TREE), "laneTree": b(S.LANE_TREE),
           "fireLane": b(S.FIRE_LANE_BOX), "towerAbove": b(S.TOWER_ABOVE)},
  "pit": {"m": SH.PIT_M, "soil": SH.SOIL_DEPTH_M, "drainage": SH.DRAINAGE_M},
  "tower": {"plate": b(T.PLATE), "core": b(T.CORE), "columns": [b(c) for c in T.COLUMNS],
            "planters": [b(p) for p in T.PLANTERS], "lift": b(T.LIFT), "lobby": b(T.LOBBY), "stair": b(T.STAIR),
            "corridor": b(T.CORRIDOR), "liftPlanter": b(T.LIFT_PLANTER), "liftShrubs": [b(p) for p in T.LIFT_SHRUBS],
            "corridorPlanters": [b(p) for p in T.CORRIDOR_PLANTERS], "roofLawn": b(T.ROOF_LAWN),
            "roofPlanters": [b(p) for p in T.ROOF_PLANTERS], "soil": T.SOIL, "floors": T.FLOORS, "typical": T.TYPICAL,
            "titles": T.TITLES}}))
`;
const py = path.join(REPO, '.venv/bin/python');
const pkg = execFileSync(fs.existsSync(py) ? py : 'python3', ['-c', PY], {cwd: REPO, encoding: 'utf8'});
fs.writeFileSync(path.join(GEN, 'package.json'), JSON.stringify(JSON.parse(pkg), null, 1));

// 2. the drawings: JPEG at the width each needs (L-6 fills the frame when the opening lands on it)
const SHEETS = {'L-6': 3072, 'L-1-revB': 2100, 'F-26-p1': 2100, 'L-102': 2400, 'L-103': 2400, 'L-104': 2400};
const src = path.join(HERE, '../public/v2/sheets');
let js = '// generated by prep.mjs: the sheets the film shows, as data URLs\nexport default {\n';
for (const [id, w] of Object.entries(SHEETS)) {
  const out = path.join(GEN, `${id}.jpg`);
  execFileSync(FFMPEG, ['-loglevel', 'error', '-y', '-i', path.join(src, `${id}.png`), '-vf', `scale=${w}:-2:flags=lanczos`, '-q:v', '2', out]);
  js += `  '${id}': 'data:image/jpeg;base64,${fs.readFileSync(out).toString('base64')}',\n`;
  fs.rmSync(out);
}
fs.writeFileSync(path.join(GEN, 'sheets.js'), js + '};\n');

// 3. the beats
const {BEATS, FIG, V2} = await import('./data.js');
// the model's own figures must be the ones the approved cards print
const c = V2.cards;
const checks = [[c[0].sub, `${FIG.typicalShrubs.toFixed(1)} m²`], [c[1].fix.text, `${FIG.roofPlanters} m²`], [c[3].sub, `${FIG.liftPlanter} m²`],
  [c[3].sub, `${FIG.overShaft.toFixed(1)} m²`], [c[4].title, `${FIG.corridorClear.toFixed(1)} m`], [c[4].fix.text, `${FIG.corridor.toFixed(1)} m`]];
for (const [text, want] of checks) if (!text.includes(want)) throw new Error(`the package says ${want}; the card says: ${text}`);
fs.writeFileSync(path.join(HERE, 'timeline.json'), JSON.stringify(BEATS, null, 1) + '\n');
console.log('gen/package.json, gen/sheets.js, timeline.json');
